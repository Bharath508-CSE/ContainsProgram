public class ContainsMethos {
    public static void main(String[] args) {
        String s1="javadev";
        System.out.println(s1.contains("j"));//true
        System.out.println(s1.contains("ava"));//true
        System.out.println(s1.contains("dev"));//true
        System.out.println(s1.contains("Java"));//false
    }
}
